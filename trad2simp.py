# 用于「这句话是不是繁体」的判定：表里所有繁体字
TRAD_CHARS = set(TRAD2SIMP)


def to_simplified(text: str) -> str:
    """逐字转换；不在表里的字原样保留。"""
    if not text:
        return text
    return "".join(TRAD2SIMP.get(c, c) for c in text)


def looks_traditional(text: str) -> bool:
    """句子里是否还有（表内的）繁体字 —— 转换后仍为 True 说明表没覆盖到。"""
    return any(c in TRAD_CHARS for c in text)
